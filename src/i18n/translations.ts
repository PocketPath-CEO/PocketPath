export const DICTS: Record<LangId, Dict> = { en, zu, xh, af, st, tn };

export function translate(lang: LangId, key: string, params?: Record<string, string | number>): string {
  const dict = DICTS[lang] ?? en;
  let str = dict[key] ?? en[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    }
  }
  return str;
}
